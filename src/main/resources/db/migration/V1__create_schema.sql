CREATE TABLE usuarios (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(255) NOT NULL,
    email       VARCHAR(255) NOT NULL,
    senha       VARCHAR(255) NOT NULL,
    role        VARCHAR(50)  NOT NULL
);

CREATE TABLE abrigos (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome               VARCHAR(255) NOT NULL,
    endereco           VARCHAR(255) NOT NULL,
    bairro             VARCHAR(255) NOT NULL,
    latitude           DOUBLE PRECISION,
    longitude          DOUBLE PRECISION,
    vagas_disponiveis  INTEGER NOT NULL,
    aberto             BOOLEAN NOT NULL
);

CREATE TABLE pontos_regua (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome              VARCHAR(255) NOT NULL,
    bairro            VARCHAR(255) NOT NULL,
    latitude          DOUBLE PRECISION,
    longitude         DOUBLE PRECISION,
    limite_alerta_cm  INTEGER NOT NULL
);

CREATE TABLE ocorrencias (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo       VARCHAR(255)  NOT NULL,
    descricao    VARCHAR(2000) NOT NULL,
    bairro       VARCHAR(255)  NOT NULL,
    nivel_cm     INTEGER       NOT NULL,
    latitude     DOUBLE PRECISION,
    longitude    DOUBLE PRECISION,
    status       VARCHAR(50)   NOT NULL,
    usuario_id   BIGINT        NOT NULL,
    criado_em    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_ocorrencias_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id)
);

CREATE TABLE leituras (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ponto_id     BIGINT      NOT NULL,
    nivel_cm     INTEGER     NOT NULL,
    origem       VARCHAR(255) NOT NULL,
    coletado_em  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_leituras_ponto FOREIGN KEY (ponto_id) REFERENCES pontos_regua (id)
);

CREATE TABLE alertas (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ponto_id   BIGINT       NOT NULL,
    nivel_cm   INTEGER      NOT NULL,
    mensagem   VARCHAR(1000) NOT NULL,
    criado_em  TIMESTAMP WITH TIME ZONE NOT NULL
);
